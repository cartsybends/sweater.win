"""Fit manpower scoring intensities from official NHL strength goals and PP TOI.

Fit completed 2023/2024 seasons; evaluate 2025 without retuning. These validate
scoring rates, not full live win calibration. Raw responses stay outside Git.
"""
import argparse,hashlib,json,math,subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.parse import urlencode

REPORTS=['powerplaytime','goalsforbystrength']
STRENGTHS={'5v4':('goalsFor5On4','timeOnIce5v4'),'4v5':('goalsFor4On5','timeOnIce5v4'),'5v3':('goalsFor5On3','timeOnIce5v3'),'3v5':('goalsFor3On5','timeOnIce5v3'),'4v3':('goalsFor4On3','timeOnIce4v3'),'3v4':('goalsFor3On4','timeOnIce4v3')}

def read(year,report,folder):
    path=folder/f'{report}-{year}.json'
    query=urlencode({'isAggregate':'false','isGame':'false','start':0,'limit':100,'cayenneExp':f'seasonId={year}{year+1} and gameTypeId=2'})
    url='https://api.nhle.com/stats/rest/en/team/'+report+'?'+query
    if not path.exists():subprocess.run(['curl','--fail','--silent','--show-error','--max-time','45',url,'-o',str(path)],check=True,timeout=50)
    raw=path.read_bytes();data=json.loads(raw)['data']
    if len(data)!=32 or len({r['teamId'] for r in data})!=32 or any(r['seasonId']!=year*10000+year+1 or r['gamesPlayed']!=82 for r in data):raise ValueError('Incomplete NHL season')
    return data,{'year':year,'report':report,'url':url,'sha256':hashlib.sha256(raw).hexdigest()}

def poisson_deviance(actual,mean):return 2*(actual*math.log(actual/mean)-actual+mean) if actual else 2*mean

def main():
    p=argparse.ArgumentParser();p.add_argument('--data',type=Path,required=True);p.add_argument('--out',type=Path,default=Path('backend/src/penalty-rates.mjs'));a=p.parse_args();a.data.mkdir(parents=True,exist_ok=True)
    with ThreadPoolExecutor(max_workers=3) as pool:rows=list(pool.map(lambda key:(key,read(*key,a.data)),[(y,r) for y in [2023,2024,2025] for r in REPORTS]))
    source={key:value[0] for key,value in rows};audit=[value[1] for _,value in rows]
    totals={}
    for year in [2023,2024,2025]:
        pp=source[year,'powerplaytime'];gf=source[year,'goalsforbystrength'];by_team={r['teamId']:r for r in pp}
        if set(by_team)!={r['teamId'] for r in gf}:raise ValueError('NHL reports contain different teams')
        for row in gf:
            if any(not isinstance(row[g],(int,float)) or not math.isfinite(row[g]) or row[g]<0 for g,_ in STRENGTHS.values()):raise ValueError('Invalid NHL goal count')
        for row in pp:
            if any(not isinstance(row[t],(int,float)) or not math.isfinite(row[t]) or row[t]<0 or row[t]>82*3600 for _,t in STRENGTHS.values()):raise ValueError('Invalid NHL strength exposure')
        # Strength-goal reports separate empty-net/extra-attacker goals; their
        # counts intentionally differ slightly from the PP conversion report.
        totals[year]={key:{'goals':sum(r[g] for r in gf),'seconds':sum(r[t] for r in pp)} for key,(g,t) in STRENGTHS.items()}
        totals[year]['baseline']={'goals':sum(r['goalsFor'] for r in gf),'games':sum(r['gamesPlayed'] for r in gf)}
    baseline=sum(totals[y]['baseline']['goals'] for y in [2023,2024])/sum(totals[y]['baseline']['games'] for y in [2023,2024])
    rates={};validation={}
    for key in STRENGTHS:
        goals=sum(totals[y][key]['goals'] for y in [2023,2024]);seconds=sum(totals[y][key]['seconds'] for y in [2023,2024]);rate=(goals+.5)/seconds
        rates[key]={'per_second':rate,'per60':rate*3600,'fit_goals':goals,'fit_seconds':seconds}
        v=totals[2025][key];expected=rate*v['seconds'];validation[key]={**v,'expected_goals':expected,'poisson_deviance':poisson_deviance(v['goals'],expected),'baseline_deviance':poisson_deviance(v['goals'],baseline/3600*v['seconds'])}
    deviance=sum(v['poisson_deviance'] for v in validation.values());base=sum(v['baseline_deviance'] for v in validation.values())
    if deviance>=base or any(not .001<r['per60']<30 for r in rates.values()):raise ValueError('NHL rate validation failed')
    result={'version':'sweater-manpower-v1','fit_seasons':[2023,2024],'validation_season':2025,'baseline_goals_per_team_game':baseline,'rates':rates,'validation':{'states':validation,'poisson_deviance':deviance,'baseline_deviance':base,'scope':'Goal-rate holdout only; not full live win-probability calibration.'},'inputs':audit,'source':'Official NHL team strength goals and power-play ice time','smoothing':'Jeffreys half-goal prior for each strength rate.'}
    a.out.write_text('// Generated by tools/playoffs/fit_penalties.py; official NHL factual inputs only.\nexport const PENALTY_RATES='+json.dumps(result,separators=(',',':'))+';\n');(a.data/'rate-validation.json').write_text(json.dumps(result,indent=2));print(json.dumps({'baseline':baseline,'rates':{k:round(v['per60'],3) for k,v in rates.items()},'validation_deviance':deviance,'baseline_deviance':base}))
if __name__=='__main__':main()
